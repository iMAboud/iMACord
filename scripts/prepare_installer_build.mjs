import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "fs";
import { join } from "path";
import { gzipSync } from "zlib";
import { computeInstallerCodeHashes, DIST_FILES, listPluginFiles, sha256Buffer } from "./installer_meta.mjs";

const rootDir = process.cwd();
const distDir = join(rootDir, "Vencord-main", "dist");
const userpluginsDir = join(rootDir, "userplugins");
const buildDir = join(rootDir, "installer_src", ".build");
const payloadDir = join(buildDir, "payload");

mkdirSync(payloadDir, { recursive: true });
for (const existing of readdirSync(payloadDir)) {
    rmSync(join(payloadDir, existing), { force: true });
}

const rawTag = (process.env.TAG_NAME || process.env.IMCORD_BUILD_VERSION || "").trim();
const version = rawTag || "dev";
const isReleaseBuild = Boolean(process.env.TAG_NAME || process.env.IMCORD_IS_RELEASE === "1");
const repo = process.env.GITHUB_REPOSITORY || "iMAboud/iMACord";

const embedded = {
    version,
    dist: {},
    plugins: {}
};

const rspLines = [
    "/resource:installer_src\\.build\\embedded_manifest.json,embedded_manifest.json"
];

let rawTotal = 0;
let gzTotal = 0;

for (const file of DIST_FILES) {
    const full = join(distDir, file);
    if (!existsSync(full)) {
        console.error(`[ERROR] Missing Vencord dist artifact: ${full}`);
        process.exit(1);
    }
    const raw = readFileSync(full);
    const gz = gzipSync(raw, { level: 9 });
    const resName = `${file}.gz`;
    writeFileSync(join(payloadDir, resName), gz);

    embedded.dist[file] = {
        hash: sha256Buffer(raw),
        size: raw.length,
        resource: resName
    };
    rspLines.push(`/resource:installer_src\\.build\\payload\\${resName},${resName}`);
    rawTotal += raw.length;
    gzTotal += gz.length;
}

const pluginFiles = listPluginFiles(rootDir);
if (pluginFiles.length === 0) {
    console.error(`[ERROR] No plugin .js files found in ${userpluginsDir}`);
    process.exit(1);
}

for (const file of pluginFiles) {
    const full = join(userpluginsDir, file);
    const raw = readFileSync(full);
    const gz = gzipSync(raw, { level: 9 });
    const resName = `${file}.gz`;
    writeFileSync(join(payloadDir, resName), gz);

    embedded.plugins[file] = {
        hash: sha256Buffer(raw),
        size: raw.length,
        resource: resName
    };
    rspLines.push(`/resource:installer_src\\.build\\payload\\${resName},${resName}`);
    rawTotal += raw.length;
    gzTotal += gz.length;
}

writeFileSync(join(buildDir, "embedded_manifest.json"), JSON.stringify(embedded, null, 2), "utf8");
writeFileSync(join(buildDir, "csc_resources.rsp"), rspLines.join("\r\n") + "\r\n", "utf8");

const { guiCodeHash, cliCodeHash } = computeInstallerCodeHashes(rootDir);
const csEsc = s => String(s).replace(/\\/g, "\\\\").replace(/"/g, "\\\"");

const buildInfoCs = `// Auto-generated by scripts/prepare_installer_build.mjs
namespace VencordInstaller
{
    internal static class BuildInfo
    {
        public const string Version = "${csEsc(version)}";
        public const bool IsReleaseBuild = ${isReleaseBuild ? "true" : "false"};
        public const string BuiltAtUtc = "${csEsc(new Date().toISOString())}";
        public const string GuiCodeHash = "${csEsc(guiCodeHash)}";
        public const string CliCodeHash = "${csEsc(cliCodeHash)}";
        public const string Repo = "${csEsc(repo)}";
    }
}
`;

writeFileSync(join(buildDir, "BuildInfo.cs"), buildInfoCs, "utf8");

const pct = rawTotal > 0 ? Math.round((gzTotal / rawTotal) * 100) : 0;
console.log(`[OK] Prepared installer payload (${DIST_FILES.length} dist, ${pluginFiles.length} plugins)`);
console.log(`     Version: ${version} (release=${isReleaseBuild})`);
console.log(`     Payload: ${(rawTotal / 1048576).toFixed(2)} MB raw -> ${(gzTotal / 1048576).toFixed(2)} MB gzip (${pct}%)`);
